const VAULT_SALT = 'ChatBoxAI_256Bit_SecureKeyStore_Salt_2026';

function xorDecode(hex: string): string {
  let str = '';
  for (let i = 0; i < hex.length; i += 2) {
    const byte = parseInt(hex.substr(i, 2), 16);
    const saltChar = VAULT_SALT.charCodeAt((i / 2) % VAULT_SALT.length);
    str += String.fromCharCode(byte ^ saltChar);
  }
  return str;
}

