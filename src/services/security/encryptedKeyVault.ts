const _decodedCache: Record<string, string[]> = {};

export function getEncryptedVaultKeys(provider: string): string[] {
  const normalized = provider.toLowerCase().trim();
  if (_decodedCache[normalized]) {
    return _decodedCache[normalized];
  }

  const ciphers = VAULT_CIPHERS[normalized];
  if (!ciphers || ciphers.length === 0) {
    return [];
  }

  const keys = ciphers.map(xorDecode);
  _decodedCache[normalized] = keys;
  return keys;
}
